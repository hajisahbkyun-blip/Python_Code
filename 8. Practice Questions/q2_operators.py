"""
Q2. Take two numbers as input. Print their :
sum, difference, product, quotient, floor division, modulus, and power.

"""

num1 = float(input("Enter the first number: ")) # covert input to float for decimal support
num2 = float(input("Enter the second number: "))

print("Sum:", num1 + num2)
print("Difference:", num1 - num2)
print("Product:", num1 * num2)
print("Quotient:", num1 / num2)
print("Floor Division:", num1 // num2)
print("Modulus:", num1 % num2)
print("Power:", num1 ** num2)
